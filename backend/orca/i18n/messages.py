def direction8(compass16: str) -> str:
    """Collapse a 16-point compass label to 8 points (NNE -> NE, ENE -> E, ...)."""
    mapping = {
        "N": "N", "NNE": "NE", "NE": "NE", "ENE": "E", "E": "E", "ESE": "SE", "SE": "SE", "SSE": "S",
        "S": "S", "SSW": "SW", "SW": "SW", "WSW": "W", "W": "W", "WNW": "NW", "NW": "NW", "NNW": "N",
    }
    return mapping.get(compass16, compass16)

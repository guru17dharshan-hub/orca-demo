export function fm(lang: FmLang, key: string, vars: Record<string, string | number> = {}): string {
  const s = FM[lang][key] ?? FM.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

/** 16-point compass → the 8 directions people say aloud. */
export function dir8(compass: string): string {
  const map: Record<string, string> = { NNE: "NE", ENE: "NE", ESE: "SE", SSE: "SE", SSW: "SW", WSW: "SW", WNW: "NW", NNW: "NW" };
  return map[compass] ?? compass;
}
